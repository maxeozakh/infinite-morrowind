import base64
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CHECKPOINT_DIR = HERE / "smol_rnn_data" / "checkpoints"
OUT_PATH = HERE / "web" / "model.js"


def main():
    if len(sys.argv) > 1:
        checkpoint_path = Path(sys.argv[1])
    else:
        checkpoint_path = sorted(CHECKPOINT_DIR.glob("*.npz"))[-1]
    ckpt = np.load(checkpoint_path)

    # float32 + base64 keeps the file ~3x smaller than printing floats as text
    tensors = {}
    for name in ["E", "Wxh", "Whh", "bh", "Why", "by", "hprev"]:
        arr = ckpt[name].astype(np.float32)
        tensors[name] = {"rows": arr.shape[0], "cols": arr.shape[1],
                         "b64": base64.b64encode(arr.tobytes()).decode()}

    model = {
        "iteration": int(ckpt["iteration"]),
        "lossCe": float(ckpt["smooth_loss"]) / int(ckpt["seq_length"]),
        "chars": [str(c) for c in ckpt["chars"]],
        "tensors": tensors,
    }
    OUT_PATH.write_text(
        "// generated by export_web_model.py from " + checkpoint_path.name + "\n"
        "window.SMOL_RNN_MODEL = " + json.dumps(model) + ";\n")
    print(f"wrote {OUT_PATH} ({OUT_PATH.stat().st_size / 1e6:.1f} MB) from {checkpoint_path.name}")


if __name__ == "__main__":
    main()
